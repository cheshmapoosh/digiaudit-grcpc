create table central_account_group_risk_assignment (
    id raw(16) not null,
    profile_id raw(16) not null,
    account_group_id raw(16) not null,
    risk_template_id raw(16) not null,
    status varchar2(32 byte) not null,
    valid_from date,
    valid_to date,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    created_by raw(16) not null,
    updated_by raw(16) not null,
    deleted_at timestamp(6) with time zone,
    deleted_by raw(16),
    version number(19,0) default 0 not null,
    constraint pk_central_agra primary key (id),
    constraint uk_central_agra_pair unique (profile_id, account_group_id, risk_template_id),
    constraint fk_central_agra_profile foreign key (profile_id) references dataset_profile(id),
    constraint fk_central_agra_group foreign key (profile_id, account_group_id)
        references central_account_group(profile_id, id),
    constraint fk_central_agra_risk foreign key (profile_id, risk_template_id)
        references central_risk_template(profile_id, id),
    constraint ck_central_agra_status check (status in ('ACTIVE', 'INACTIVE', 'DELETED')),
    constraint ck_central_agra_valid check (valid_to is null or valid_from is null or valid_from <= valid_to),
    constraint ck_central_agra_deleted check (
        (status = 'DELETED' and deleted_at is not null and deleted_by is not null)
        or (status <> 'DELETED' and deleted_at is null and deleted_by is null)
    )
);

create index ix_central_agra_risk on central_account_group_risk_assignment(profile_id, risk_template_id);

